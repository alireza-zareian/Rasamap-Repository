// Remove the route types that earlier builds left in every Next dist folder.
//
// `next build` type-checks every folder tsconfig.json includes, and Next adds
// the types of each dist folder it has built into — .next, .next-test,
// .next-e2e — to that list. Those files describe the routes as they were at
// that build. Once a route moves or is deleted, a later build in *another*
// folder type-checks the stale copy and fails ("Type 'Route' does not satisfy
// the constraint 'LayoutRoutes'") on code that is fine. That happened here after
// the public pages moved into app/(site): `npm run demo` would have stopped at
// the build. The types are regenerated by the build that needs them, so
// removing them first costs nothing.

import { readdirSync, rmSync } from "node:fs";

for (const dir of readdirSync(".").filter(d => d.startsWith(".next"))) {
  rmSync(`${dir}/types`, { recursive: true, force: true });
  rmSync(`${dir}/dev/types`, { recursive: true, force: true });
}
