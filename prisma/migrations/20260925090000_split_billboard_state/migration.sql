-- Split the billboards table along the questions it was answering at once.
--
-- 1. `status` answered two things: whether the board is free (available,
--    busy, reserved, inactive) and whether the listing has passed review
--    (pending, awaiting_payment, needs_revision, rejected). It becomes two
--    columns, `availability` and `moderation`. A row in a review state keeps
--    that state as its moderation and is `available`; every other row is
--    `approved` and keeps its status as its availability.
--
-- 2. The crawler's bookkeeping (url, structureCode, scrapedAt, the sync
--    snapshot, missingSince) moves to `billboard_sources`, one row per crawled
--    billboard. Listings and admin-created rows have no source and get none.
--
-- 3. Columns nothing reads are dropped: `icon` (the UI draws the type's own
--    icon), `mapX`/`mapY` (percentages on a decorative map that was replaced
--    by real coordinates), and `ownerId` with the `owners` table, which no
--    write path ever populated outside the demo seed.
--
-- 4. Review replies and audit rows get real foreign keys for their actor:
--    `review_replies.staffId` → admins, `audit_logs.userId` → users. Audit
--    rows written before `adminId` was filled in carried the actor in
--    details.actorId; those are linked where the account still exists.
--
-- Generated by `prisma migrate diff`, then edited where marked "hand-written":
-- SQLite rebuilds a table to drop a column, so the data moves have to happen
-- while the old table still exists, and the partial unique index Prisma cannot
-- see (20260902140000) has to be recreated on the rebuilt table.

