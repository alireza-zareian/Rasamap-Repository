CREATE TABLE "billboard_sources" (
    "billboardId" INTEGER NOT NULL PRIMARY KEY AUTOINCREMENT,
    "url" TEXT,
    "structureCode" TEXT,
    "scrapedAt" TEXT,
    "snapshot" JSONB,
    "missingSince" DATETIME,
    CONSTRAINT "billboard_sources_billboardId_fkey" FOREIGN KEY ("billboardId") REFERENCES "billboards" ("id") ON DELETE CASCADE ON UPDATE CASCADE
);

-- hand-written: every crawled row's bookkeeping, before its columns are dropped.
INSERT INTO "billboard_sources" ("billboardId", "url", "structureCode", "scrapedAt", "snapshot", "missingSince")
SELECT "id", "url", "structureCode", "scrapedAt", "sourceSnapshot", "missingSince"
FROM "billboards"
WHERE "source" IS NOT NULL AND "source" NOT IN ('listing', 'manual');

